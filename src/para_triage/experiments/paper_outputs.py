"""Turns runs/e1 (and later runs/e7) into the tables, figures and macros the papers include.

    python -m para_triage.experiments.paper_outputs --runs runs --paper paper

Everything written here is generated: never edit it by hand, rerun this script. Figures need
matplotlib (`pip install .[plots]`). Labels come from the same rules as the baseline, so no output
calls a number "accuracy against ground truth"; the captions are written in the papers.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .paper_state import VARIANT, figname, variant  # noqa: F401  (figname is used by the E7 writers)

SYSTEM_LABEL = {
    "rules": "Rules",
    "rules_imp": "Rules + imputation",
    "gb": "Gradient boosting",
    "mlp": "MLP",
    "hybrid": "Hybrid (rules, MLP if they abstain)",
}
BASELINES = ("rules", "rules_imp", "gb")
DEFAULT = (1.0, 1.0)
CLEAN = (0.0, 0.0)
HEADER = "% Generated by para_triage.experiments.paper_outputs from {src}. Do not edit by hand.\n"

_VARIANT = VARIANT  # shared with the modules that write E7; see paper_state


def load_e1(runs: Path, e1_name: str = "e1") -> dict[str, pd.DataFrame]:
    out = {name: pd.read_csv(runs / e1_name / f"{name}.csv") for name in ("results", "extras", "by_group")}
    return out


def cell(df: pd.DataFrame, train: tuple, test: tuple) -> pd.DataFrame:
    return df[
        (df.train_noise == train[0]) & (df.train_missing == train[1]) & (df.test_noise == test[0]) & (df.test_missing == test[1])
    ]


def per_seed(df: pd.DataFrame, system: str, column: str, train: tuple, test: tuple) -> pd.Series:
    sub = cell(df, train, test)
    sub = sub[sub.system == system] if "system" in sub else sub
    return sub.set_index("seed")[column].sort_index()


def mean_sd(series: pd.Series) -> tuple[float, float]:
    return float(series.mean()), float(series.std(ddof=1)) if len(series) > 1 else 0.0


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"


def pm(series: pd.Series, digits: int = 1) -> str:
    m, s = mean_sd(series)
    return f"{pct(m, digits)} $\\pm$ {pct(s, digits)}"


def write(path: Path, text: str) -> None:
    if _VARIANT["file"] and path.name[:2] in ("t_", "f_"):
        path = path.with_name(figname(path.name))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


# ---------------------------------------------------------------- tables

def table_main(e1: dict, systems: tuple[str, ...], full: bool) -> str:
    res = e1["results"]
    rows = []
    for s in systems:
        acc = per_seed(res, s, "accuracy", DEFAULT, DEFAULT)
        f1 = per_seed(res, s, "macro_f1", DEFAULT, DEFAULT)
        line = f"{SYSTEM_LABEL[s]} & {pm(acc)} & {pm(f1)}"
        if full:
            if s in ("rules", "rules_imp"):
                line += f" & {pm(per_seed(res, s, 'coverage', DEFAULT, DEFAULT))} & {pm(per_seed(res, s, 'accuracy_decided', DEFAULT, DEFAULT))}"
            else:
                line += " & 100.0 & --"
        rows.append(line + " \\\\")
    cols = "lcc" + ("cc" if full else "")
    head = "System & Accuracy (\\%) & Macro-F1 (\\%)" + (" & Decides (\\%) & Accuracy where it decides (\\%)" if full else "")
    return f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head} \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"


def table_mismatch(e1: dict) -> str:
    res = e1["results"]
    systems = ("rules", "rules_imp", "gb", "mlp")
    levels_n = sorted(res.test_noise.unique())
    levels_m = sorted(res.test_missing.unique())
    head = "Noise & Missing & " + " & ".join(SYSTEM_LABEL[s] for s in systems) + " \\\\"
    lines = []
    for n in levels_n:
        for m in levels_m:
            vals = [pm(per_seed(res, s, "accuracy", DEFAULT, (n, m))) for s in systems]
            lines.append(f"{n:g}$\\times$ & {m:g}$\\times$ & " + " & ".join(vals) + " \\\\")
    clean = [pm(per_seed(res, s, "accuracy", CLEAN, DEFAULT)) for s in ("gb", "mlp")]
    lines.append("\\midrule")
    lines.append("\\multicolumn{2}{l}{Trained at $0\\times$, $0\\times$; tested at $1\\times$, $1\\times$} & -- & -- & " + " & ".join(clean) + " \\\\")
    return f"\\begin{{tabular}}{{cc{'c' * len(systems)}}}\n\\toprule\n{head}\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"


def table_group(e1: dict) -> str:
    g = e1["by_group"]
    sub = g[(g.train_noise == 1) & (g.train_missing == 1) & (g.test_noise == 1) & (g.test_missing == 1)]
    systems = ("rules", "mlp", "hybrid")
    lines = []
    for group in sorted(sub.group.unique()):
        vals = [pm(sub[(sub.group == group) & (sub.system == s)].set_index("seed")["accuracy"]) for s in systems]
        lines.append(f"{group.replace('_', ' ')} & " + " & ".join(vals) + " \\\\")
    head = "Group & " + " & ".join(SYSTEM_LABEL[s].split(" (")[0] for s in systems) + " \\\\"
    return f"\\begin{{tabular}}{{lccc}}\n\\toprule\n{head}\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"


# ---------------------------------------------------------------- numbers

def best_baseline(res: pd.DataFrame, c: tuple) -> str:
    """The baseline with the best mean accuracy in matched cell `c`."""
    means = {s: per_seed(res, s, "accuracy", c, c).mean() for s in BASELINES}
    return max(means, key=means.get)


def paired_gap(res: pd.DataFrame, c: tuple, against: str | None = None) -> pd.Series:
    """MLP minus a baseline, in accuracy, per seed, on the same held-out rows (matched cell)."""
    against = against or best_baseline(res, c)
    return per_seed(res, "mlp", "accuracy", c, c) - per_seed(res, against, "accuracy", c, c)


def macro(name: str, value: str, comment: str = "") -> str:
    # providecommand + renewcommand: works whether or not numbers.tex already defined the name
    tail = f" % {comment}" if comment else ""
    suffix = _VARIANT["macro"]
    names = [name, name + suffix] if suffix == "Row" else [name + suffix]
    return "".join(f"\\providecommand{{\\{n}}}{{}}\\renewcommand{{\\{n}}}{{{value}}}{tail}\n" for n in names)


def numbers_e1(e1: dict, runs: Path, seeds: list[int], e1_name: str = "e1") -> str:
    res, ex = e1["results"], e1["extras"]
    cfg = json.loads((runs / e1_name / "config.json").read_text(encoding="utf-8")) if (runs / e1_name / "config.json").exists() else {}
    src = f"runs/{e1_name}/results.csv"
    out = [HEADER.format(src=f"runs/{e1_name}")]

    sizes = np.load(runs / e1_name / f"seed_{seeds[0]}" / "split.npz")
    n_rows = sum(len(sizes[k]) for k in ("train", "val", "cal", "test"))
    thousands = f"{n_rows:,}".replace(",", "{,}")
    out += [
        macro("nRows", thousands, "rows per seed"),
        macro("nRuns", str(len(seeds)), "seeds"),
        macro("nTrain", str(len(sizes["train"]))),
        macro("nVal", str(len(sizes["val"]))),
        macro("nCal", str(len(sizes["cal"]))),
        macro("nTest", str(len(sizes["test"]))),
        macro("nGrid", str(len(res[["test_noise", "test_missing"]].drop_duplicates())), "noise x missing cells"),
        macro("noiseLevels", ", ".join(f"{v:g}" for v in sorted(res.test_noise.unique()))),
        macro("missLevels", ", ".join(f"{v:g}" for v in sorted(res.test_missing.unique()))),
    ]
    for s, tag in (("rules", "Rules"), ("rules_imp", "RulesImp"), ("gb", "GB"), ("mlp", "MLP"), ("hybrid", "Hybrid")):
        a, sd = mean_sd(per_seed(res, s, "accuracy", DEFAULT, DEFAULT))
        out += [macro(f"acc{tag}", pct(a), src), macro(f"sd{tag}", pct(sd), src)]
        out.append(macro(f"fOne{tag}", pm(per_seed(res, s, "macro_f1", DEFAULT, DEFAULT)), src))
    out += [
        macro("covRules", pct(per_seed(res, "rules", "coverage", DEFAULT, DEFAULT).mean()), src),
        macro("accRulesDecided", pct(per_seed(res, "rules", "accuracy_decided", DEFAULT, DEFAULT).mean()), src),
    ]
    e = ex[(ex.train_noise == 1) & (ex.train_missing == 1) & (ex.test_noise == 1) & (ex.test_missing == 1)].set_index("seed")
    out += [
        macro("accMLPDecided", pct(e["mlp_accuracy_rules_decided"].mean()), "runs/e1/extras.csv"),
        macro("accMLPAbstain", pct(e["mlp_accuracy_rules_abstain"].mean()), "runs/e1/extras.csv"),
        macro("accGBAbstain", pct(e["gb_accuracy_rules_abstain"].mean()), "runs/e1/extras.csv"),
        macro("ece", f"{e['mlp_ece'].mean():.3f}", "runs/e1/extras.csv"),
        macro("topTwo", pct(e["mlp_top2"].mean()), "runs/e1/extras.csv"),
    ]
    for name, c in (("NoMissing", (1.0, 0.0)), ("DoubleMissing", (1.0, 2.0)), ("NoNoise", (0.0, 1.0)), ("DoubleNoise", (2.0, 1.0))):
        gap = paired_gap(res, c, "rules")
        m, s = mean_sd(gap)
        out.append(macro(f"adv{name}", f"{100 * m:+.1f}", f"MLP minus rules, points, cell {c}, sd {100 * s:.1f}, {src}"))
    out += [
        macro("rulesCeilingCheck", pct(per_seed(res, "rules", "accuracy", CLEAN, CLEAN).mean()), "built in: no noise, nothing missing"),
        macro("mlpFidelityClean", pct(per_seed(res, "mlp", "accuracy", CLEAN, CLEAN).mean()), "learned fidelity to the rules without noise"),
    ]
    if cfg:
        out.append(macro("nTuningConfigs", str(len(cfg.get("mlp_grid", []))), "configurations per model, chosen on validation"))
    return "".join(out)


# ---------------------------------------------------------------- figures

def figures_e1(e1: dict, fig_dir: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    res = e1["results"]
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42})
    style = {  # colour-blind safe, distinguishable in greyscale by marker and dashing
        "rules": ("#000000", "o"),
        "rules_imp": ("#E69F00", "s"),
        "gb": ("#009E73", "^"),
        "mlp": ("#0072B2", "D"),
        "hybrid": ("#CC79A7", "v"),
    }
    levels = sorted(res.test_noise.unique())
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.4), sharey=True)
    for ax, axis, title in ((axes[0], "noise", "Measurement noise (missing fields at $1\\times$)"), (axes[1], "missing", "Missing fields (noise at $1\\times$)")):
        for s, (color, marker) in style.items():
            for matched in (True, False):
                if not matched and s == "rules":
                    continue  # the rules have nothing to train
                means, sds = [], []
                for lv in levels:
                    c = (lv, 1.0) if axis == "noise" else (1.0, lv)
                    train = c if matched else DEFAULT
                    series = per_seed(res, s, "accuracy", train, c)
                    m, sd = mean_sd(series)
                    means.append(100 * m)
                    sds.append(100 * sd)
                means, sds = np.array(means), np.array(sds)
                ax.plot(levels, means, color=color, marker=marker, ms=4, lw=1.4, ls="-" if matched else "--",
                        alpha=1.0 if matched else 0.7, label=SYSTEM_LABEL[s].split(" (")[0] if matched else None)
                if matched:
                    ax.fill_between(levels, means - sds, means + sds, color=color, alpha=0.15, lw=0)
        ax.set_xlabel(f"{title}\nmultiplier of the default rate")
        ax.set_xticks(levels)
        ax.set_xticklabels([f"{v:g}$\\times$" for v in levels])
        ax.grid(alpha=0.25)
    axes[0].set_ylabel("Agreement with rules' label (%)")
    handles, labels = axes[0].get_legend_handles_labels()
    from matplotlib.lines import Line2D

    handles += [Line2D([], [], color="gray", ls="-"), Line2D([], [], color="gray", ls="--")]
    labels += ["solid: trained at the tested level", "dashed: trained at $1\\times$, $1\\times$"]
    fig.legend(handles, labels, loc="lower center", ncol=3, frameon=False, fontsize=8)
    fig.tight_layout(rect=(0, 0.2, 1, 1))
    fig_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(fig_dir / figname("f_sweep.pdf"))
    plt.close(fig)

    # F-grid: paired MLP minus the best baseline of each cell
    noise_levels, miss_levels = sorted(res.test_noise.unique()), sorted(res.test_missing.unique())
    gap_m = np.zeros((len(noise_levels), len(miss_levels)))
    gap_s = np.zeros_like(gap_m)
    names = [[None] * len(miss_levels) for _ in noise_levels]
    for i, n in enumerate(noise_levels):
        for j, m in enumerate(miss_levels):
            c = (n, m)
            names[i][j] = best_baseline(res, c)
            mean, sd = mean_sd(paired_gap(res, c))
            gap_m[i, j], gap_s[i, j] = 100 * mean, 100 * sd
    fig, ax = plt.subplots(figsize=(4.6, 3.6))
    bound = max(1.0, np.abs(gap_m).max())
    im = ax.imshow(gap_m, cmap="RdBu", vmin=-bound, vmax=bound, origin="lower")
    for i in range(len(noise_levels)):
        for j in range(len(miss_levels)):
            dark = abs(gap_m[i, j]) > 0.6 * bound
            ax.text(j, i, f"{gap_m[i, j]:+.1f}\n$\\pm${gap_s[i, j]:.1f}", ha="center", va="center", fontsize=7.5,
                    color="white" if dark else "black")
    ax.set_xticks(range(len(miss_levels)), [f"{v:g}$\\times$" for v in miss_levels])
    ax.set_yticks(range(len(noise_levels)), [f"{v:g}$\\times$" for v in noise_levels])
    ax.set_xlabel("Missing-field multiplier")
    ax.set_ylabel("Noise multiplier")
    fig.colorbar(im, ax=ax, label="MLP minus best baseline (points)")
    fig.tight_layout()
    fig.savefig(fig_dir / figname("f_grid.pdf"))
    plt.close(fig)
    write(fig_dir / "f_grid_best_baseline.csv", pd.DataFrame(names, index=noise_levels, columns=miss_levels).to_csv())


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=Path, default=Path("runs"))
    parser.add_argument("--paper", type=Path, default=Path("paper"), help="root of the output folders (p1/ and p4/ below it); created if missing")
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args(argv)

    p1, p4 = args.paper / "p1", args.paper / "p4"
    numbers, done, seeds = "", [], []
    # E1 and E7 are written for each split of the rows: by row (plain macro names and suffix Row, plain file
    # names) and by new profile (suffix NewProfile, files with _newprofile).
    for e1_name, e7_name, macro_suffix, file_suffix in (("e1", "e7", "Row", ""), ("e1_profile", "e7_profile", "NewProfile", "_newprofile")):
        if not (args.runs / e1_name / "results.csv").exists():
            continue
        with variant(macro_suffix, file_suffix):
            e1 = load_e1(args.runs, e1_name)
            seeds = sorted(e1["results"].seed.unique().tolist())
            src = f"runs/{e1_name}"
            write(p1 / "tables" / "t_main.tex", HEADER.format(src=f"{src}/results.csv") + table_main(e1, ("rules", "rules_imp", "gb", "mlp", "hybrid"), full=True))
            write(p4 / "tables" / "t_main.tex", HEADER.format(src=f"{src}/results.csv") + table_main(e1, ("rules", "mlp", "hybrid"), full=False))
            write(p1 / "tables" / "t_mismatch.tex", HEADER.format(src=f"{src}/results.csv") + table_mismatch(e1))
            write(p1 / "tables" / "t_group.tex", HEADER.format(src=f"{src}/by_group.csv") + table_group(e1))
            numbers += ("\n" if numbers else "") + numbers_e1(e1, args.runs, seeds, e1_name)
            done.append(f"E1 ({macro_suffix})")
            have_e7 = (args.runs / e7_name / "marginal.csv").exists()
            if have_e7:
                from . import paper_outputs_e7 as e7mod

                e7 = e7mod.load_e7(args.runs, e7_name)
                src7 = f"runs/{e7_name}/*.csv"
                write(p1 / "tables" / "t_selective.tex", HEADER.format(src=src7) + e7mod.table_selective(e7))
                write(p1 / "tables" / "t_conformal.tex", HEADER.format(src=src7) + e7mod.table_conformal(e7))
                write(p1 / "tables" / "t_class.tex", HEADER.format(src=src7) + e7mod.table_class(e7))
                numbers += "\n" + e7mod.numbers_e7(e7, args.runs)
                done.append(f"E7 ({macro_suffix})")
            if not args.no_figures:
                figures_e1(e1, p1 / "figures")
                if have_e7:
                    e7mod.figures_e7(e7, p1 / "figures")
    sentinel = {"v1": "accuracy.csv", "e2": "results.csv", "e3": "scenarios.csv", "emnar": "results.csv", "v7": "marginal.csv"}
    for name, file in sentinel.items():  # later experiments: written only when their results exist
        if (args.runs / name / file).exists():
            import importlib

            module = importlib.import_module(f".paper_outputs_{name}", __package__)
            numbers += "\n" + module.write_outputs(args.runs, args.paper, not args.no_figures)
            done.append(name.upper())
    write(p1 / "numbers_exp.tex", numbers)
    write(p4 / "numbers_exp.tex", numbers)
    print(f"wrote tables, numbers_exp.tex and figures for seeds {seeds}: " + ", ".join(done))


if __name__ == "__main__":
    main()
