"""Writes `class_table.py`: for every decided combination (4 limb levels and a posture), the classes the rule engine says are
MET and the ones it says are BORDERLINE. Needs `pyyaml` (the rule engine loads a YAML catalog), which the `k34-models`
environment does not have, so this is run ONCE in the project environment (read only; nothing is installed or changed):

    PYTHONPATH=src;spikes  <para-triage python> -m k35.make_class_table

A test (tests/test_k35_classes.py) compares the table with the engine on every combination.
"""
from __future__ import annotations

import itertools
from pathlib import Path

from para_triage.rules import RuleEngine
from para_triage.rules.schema import Impairment, LowerLimbLevel, Posture, Profile, Status, UpperLimbLevel

POSTURES = {"standing": Posture.STANDING, "prosthesis": Posture.PROSTHESIS, "seated": Posture.SEATED}


def engine_classes(engine: RuleEngine, posture: str, ll, lr, ul, ur):
    """(meets, borderline) from the engine. A level of `?` is passed as None (not informed)."""
    def f(value, enum):
        return None if value == "?" else enum(value)

    profile = Profile(impairments=frozenset({Impairment.LIMB_DEFICIENCY}), posture=POSTURES[posture],
                      lower_left=f(ll, LowerLimbLevel), lower_right=f(lr, LowerLimbLevel), upper_left=f(ul, UpperLimbLevel), upper_right=f(ur, UpperLimbLevel))
    result = engine.evaluate(profile)
    return tuple(result.meets), tuple(result.with_status(Status.BORDERLINE))


def main() -> None:
    engine = RuleEngine()
    rows = []
    for posture in POSTURES:
        for ll, lr, ul, ur in itertools.product(range(4), range(4), range(3), range(3)):
            meets, borderline = engine_classes(engine, posture, ll, lr, ul, ur)
            if meets or borderline:
                rows.append((posture, ll, lr, ul, ur, meets, borderline))
    lines = ['"""GENERATED by make_class_table.py from the rule engine. Do not edit by hand.', "",
             "Key: (posture, lower_left, lower_right, upper_left, upper_right). Value: (classes met, classes borderline).",
             "A key that is not here means the engine gives NO class (empty set) for that decided combination.", '"""', "TABLE = {"]
    lines += [f"    {r[:5]!r}: ({r[5]!r}, {r[6]!r})," for r in rows]
    lines.append("}")
    (Path(__file__).parent / "class_table.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(rows), "non-empty entries of", 3 * 144)


if __name__ == "__main__":
    main()
